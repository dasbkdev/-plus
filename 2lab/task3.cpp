#include "../common/input.h"
#include <fstream>

// Двусвязный динамический стек (LIFO): каждый узел знает и о следующем, и о предыдущем
class Stack {
private:
    struct Node {
        int wagon;
        Node* next;
        Node* prev; // Нужен для двусвязной структуры
    };
    Node* top = nullptr; // Хранит адрес вершины; nullptr означает, что стек пуст

public:
    // Добавление элемента на вершину стека
    void push(int wagon) {
        // Создаем узел в куче: wagon — значение, top — ссылка на старую вершину (становится next), prev пока nullptr
        Node* node = new Node{wagon, top, nullptr}; 
        
        if (top != nullptr) {
            // Если стек не был пуст, связываем старую вершину с новым узлом через prev, сохраняя двусвязность
            top->prev = node; 
        }
        
        // Перемещаем указатель вершины на свежесозданный узел (он стал новым верхом)
        top = node; 
    }

    // Извлечение элемента с вершины стека через передачу по ссылке (&wagon)
    bool pop(int& wagon) {
        // Если вершина указывает в никуда — извлекать нечего
        if (top == nullptr) return false;

        // Фиксируем адрес текущей вершины, чтобы не потерять его после сдвига top
        Node* old = top; 
        wagon = top->wagon; // Копируем значение из узла наружу по ссылке
        top = top->next; // Сдвигаем вершину на один шаг ниже по цепочке next

        if (top != nullptr) {
            // Новая вершина теперь самая верхняя, поэтому у нее больше нет узла выше (prev = nullptr)
            top->prev = nullptr; 
        }

        delete old; // Освобождаем память в куче по адресному указателю удаленного узла
        return true;
    }

    // Полная очистка стека до нулевого состояния
    void clear() {
        int wagon;
        // Пошагово извлекаем и удаляем элементы из динамической памяти, пока pop() не вернет false
        while (pop(wagon)); 
    }

    // Вывод содержимого от вершины к основанию
    void show() const {
        cout << "Вершина -> ";
        Node* current = top; // Берем локальный указатель для итерации, чтобы не потерять адрес самoй вершины top
        
        // Переходим по указателям next от узла к узлу, пока не упремся в nullptr (конец стека)
        while (current != nullptr) {
            cout << current->wagon << ' ';
            current = current->next; // Сдвигаем указатель итератора на следующий узел
        }
        if (top == nullptr) cout << "пусто";
        cout << '\n';
    }

    // Загрузка состава с валидацией данных (из консоли или файла)
    bool input() {
        int wagons[100], count;
        int mode = readInt("1 - клавиатура, 2 - файл: ", 1, 2);

        if (mode == 1) {
            count = readInt("Количество вагонов (0..100): ", 0, 100);
            for (int i = 0; i < count; i++) {
                wagons[i] = readInt("Тип вагона (1 или 2): ", 1, 2);
            }
        } else {
            string path = readText("Путь к файлу: ", 250);
            ifstream file(path);

            // Читаем количество и сразу проверяем открытие файла, успешность считывания (file >> count) и диапазон
            if (!file || !(file >> count) || count < 0 || count > 100) {
                cout << "Ошибка открытия файла или количества вагонов.\n";
                return false;
            }

            // Чтение типов вагонов с проверкой потока ввода и валидности значений
            for (int i = 0; i < count; i++) {
                if (!(file >> wagons[i]) || (wagons[i] != 1 && wagons[i] != 2)) {
                    cout << "Ошибка: каждый вагон должен иметь тип 1 или 2.\n";
                    return false;
                }
            }

            // Пытаемся считать еще один токен: если удалось, значит в файле есть незапланированный хвост данных
            string extra;
            if (file >> extra) {
                cout << "Ошибка: лишние данные в файле.\n";
                return false;
            }
        }

        // Гарантируем "атомарность": очищаем существующий стек только после полного прохождения всех проверок ввода
        clear(); 
        
        // Заполняем стек считанными элементами из массива
        for (int i = 0; i < count; i++) {
            push(wagons[i]);
        }
        return true;
    }

    // Распределение вагонов исходного стека по двум целевым стекам (сортировка по типу)
    void divide(Stack& first, Stack& second) {
        // Передача по ссылке (&) позволяет изменять внешние объекты first и second напрямую, поэтому сначала обнуляем их
        first.clear();
        second.clear();
        int wagon;

        // Алгоритм с опустошением: поштучно забираем вагоны с вершины текущего стека (pop) и перекладываем в нужный
        while (pop(wagon)) {
            if (wagon == 1) {
                first.push(wagon);
            } else {
                second.push(wagon);
            }
        }
    }

    // Деструктор: автоматически вызывается при уничтожении экземпляра (например, при выходе из области видимости)
    ~Stack() {
        // Освобождает всю выделенную через new память, чтобы предотвратить утечку ресурсов (memory leak)
        clear(); 
    }
};

int main() {
    Stack train, first, second;

    while (true) {
        cout << "\n1 - сформировать состав, 2 - показать, 3 - разделить, 0 - выход\n";
        int menu = readInt("Выбор: ", 0, 3);

        if (menu == 0) break;

        if (menu == 1) {
            // Если input() завершился с ошибкой, прошлые результаты не сбрасываются; если успешно — очищаем приемники
            if (train.input()) {
                first.clear();
                second.clear();
            }
        }
        if (menu == 2) {
            cout << "Общий: ";
            train.show();
        }
        if (menu == 3) {
            cout << "До разделения: ";
            train.show();

            // Передаем объекты по ссылке: train внутри divide() полностью опустошится, а first и second заполнятся
            train.divide(first, second); 

            cout << "Общий после разделения: ";
            train.show();
            cout << "Направление 1: ";
            first.show();
            cout << "Направление 2: ";
            second.show();
        }
    }
}